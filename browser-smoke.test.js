import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import {createServer} from 'node:http';
const html=await readFile(new URL('./dist/index.html',import.meta.url));
const server=createServer((_request,response)=>{response.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});response.end(html)});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const baseURL=`http://127.0.0.1:${server.address().port}/`;
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[], requests=[];
 page.on('pageerror', e=>errors.push(e.message));
 page.on('request', r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(baseURL)) requests.push(r.url())});
 await page.goto(baseURL);
 await page.waitForFunction(()=>document.documentElement.dataset.sceneAgents==='35',{timeout:20000});
 assert.equal(await page.locator('#viewport canvas').count(),1);
 assert.equal(await page.locator('#scene-error').isVisible(),false);
 assert.equal(await page.locator('.room-label').count(),6);
 assert.equal(await page.locator('.market-pills > span').count(),2);
 assert.deepEqual(await page.locator('.market-pills > span').allTextContents(),[' ORO',' NASDAQ']);
 await page.waitForTimeout(1500);
 await page.screenshot({path:'/tmp/cardenas-desktop.png',fullPage:true});
 await page.locator('.room-label').first().click();
 await page.locator('#team-dialog').waitFor({state:'visible'});
 assert.equal(await page.locator('#dialog-body .roster-agent').count(),7);
 await page.locator('#open-team').click();
 assert.match(await page.locator('#detail-title').textContent(),/Investigación/);
 await page.locator('#run-button').click();
 await page.waitForTimeout(4000);
 await page.locator('#run-button').click();
 assert.match(await page.locator('#lab-state').textContent(),/espera/);
 await page.locator('[data-page="testing"]').click();
 assert.equal(await page.locator('#detail-content .account-equity').count(),6);
 await page.locator('[data-page="news"]').click();
 await page.locator('#news-block').check();
 assert.equal(await page.locator('#news-block').isChecked(),true);
 assert.match(await page.locator('#state-detail').textContent(),/Filtro de noticias/);
 await page.locator('[data-page="risk"]').click();
 await page.locator('#step-button').click();
 await page.locator('#emergency-button').click();
 assert.equal(await page.locator('#run-button').isDisabled(),true);
 assert.equal(await page.locator('#lab-state').textContent(),'Detenido');
 await page.locator('#reset-lab').click();
 await page.locator('#confirm-reset').click();
 assert.equal(await page.locator('#run-button').isEnabled(),true);
 assert.equal(await page.locator('#total-equity').textContent(),'$600,000.00');
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#report-button').click();
 const download=await downloadPromise;
 const report=JSON.parse(await readFile(await download.path(),'utf8'));
 assert.equal(report.accounts.length,6);
 const counts=new Map();
 for(const account of report.accounts)counts.set(account.marketId,(counts.get(account.marketId)||0)+1);
 assert.deepEqual([...counts.keys()].sort(),['NDAQ.QQ','XAUSD']);
 assert.deepEqual([...counts.values()],[3,3]);
 assert.match(report.dataSource,/^synthetic-/);
 await page.locator('[data-page="office"]').click();
 await page.locator('#animation-button').click();
 assert.equal(await page.locator('#animation-button').getAttribute('aria-pressed'),'false');
 await page.locator('#zoom-in').click();
 await page.locator('#reset-camera').click();
 await page.locator('#integration-button').click();
 assert.match(await page.locator('#dialog-body').textContent(),/MetaTrader|METATRADER/);
 assert.match(await page.locator('#dialog-body').textContent(),/Deriv/i);
 assert.match(await page.locator('#dialog-body').textContent(),/XAUSD/);
 assert.match(await page.locator('#dialog-body').textContent(),/NDAQ\.QQ/);
 await page.locator('#integration-close').click();
 assert.deepEqual(errors,[]);
 assert.deepEqual(requests,[]);
 await page.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
 await mobile.goto(baseURL);
 await mobile.waitForFunction(()=>document.documentElement.dataset.sceneAgents==='35');
 const overflow=await mobile.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(overflow.scroll<=overflow.width,JSON.stringify(overflow));
 await mobile.screenshot({path:'/tmp/cardenas-mobile.png',fullPage:true});
 for(const id of ['research','testing','risk','development','news','operators']) {
  await mobile.locator(`[data-page="${id}"]`).click();
  const over=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(over,false,`mobile overflow ${id}`);
 }
 console.log('PASS: 35 agentes, WebGL, seis salas, modal/navegación, seis demos, inicio/pausa, noticias, paso manual, emergencia/reset, exportación JSON, integración, animación y cámara, móvil sin overflow, dos mercados Deriv XAUSD/NDAQ.QQ, sin errores JS ni solicitudes externas.');
} finally {await browser.close();await new Promise(resolve=>server.close(resolve))}
